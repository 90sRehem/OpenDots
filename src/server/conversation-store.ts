export type MessageRole = 'user' | 'assistant' | 'system' | 'tool';
/**
 * Who started a run, recorded by the server at admission and never read from
 * client metadata. `web_owner` is the only source that can seed learning.
 */
export type AdmittedRunSource =
  | 'web_owner'
  | 'channel_owner'
  | 'scheduled_task'
  | 'voice_compute'
  | 'voice_receipt';
/** Server-initiated turns that share the runner but are never owner web evidence. */
export type ServerTurnSource = Extract<
  AdmittedRunSource,
  'scheduled_task' | 'voice_compute' | 'voice_receipt'
>;
/** `unknown` marks runs recorded before provenance existed; they are never eligible. */
export type RunSource = AdmittedRunSource | 'unknown';
export interface ConversationMessage {
  id: string;
  threadId: string;
  dotId: string;
  ownerId: string;
  ordinal: number;
  role: MessageRole;
  content: unknown;
  toolCallId: string | null;
  toolResult: unknown;
  metadata: unknown;
  createdAt: number;
}
export type RunStatus = 'running' | 'completed' | 'failed' | 'interrupted';
export interface ConversationRun {
  id: string;
  threadId: string;
  status: RunStatus;
  startedAt: number;
  finishedAt: number | null;
  error: string | null;
  source: RunSource;
  /** Ordinals of the messages admitted or generated by this run; null when unrecorded. */
  firstOrdinal: number | null;
  lastOrdinal: number | null;
}
export interface LearningJobCandidate {
  signal: LearningSignal;
  evidence: LearningEvidenceRecord[];
  sourceDigest: string;
  /** Required for `repeated_workflow` and absent for every other signal. */
  patternHash?: string | null;
}
/** A canonical message with the digest of its stored content, which evidence records cite. */
export interface DigestedMessage {
  message: ConversationMessage;
  sha256: string;
}
export type LearningJobSkip =
  | 'run_not_completed'
  | 'invalid_candidate'
  | 'source_not_eligible'
  | 'unbounded_run'
  | 'unowned_thread'
  | 'not_enrolled'
  | 'dot_not_enabled'
  | 'duplicate_run'
  | 'evidence_unverified'
  | 'queue_full'
  | 'job_capacity'
  | 'storage_budget'
  | 'learning_unavailable';
export interface LearningJob {
  id: string;
  ownerId: string;
  dotId: string;
  threadId: string;
  sourceRunId: string;
  signal: LearningSignal;
  state:
    | 'queued'
    | 'running'
    | 'completed'
    | 'no_change'
    | 'failed'
    | 'interrupted'
    | 'cancelled';
  evidence: LearningEvidenceRecord[];
  sourceDigest: string;
  patternHash: string | null;
  consentRevision: number;
  lease: string | null;
  startedAt: number | null;
  finishedAt: number | null;
  reservedInputTokens: number;
  reservedOutputTokens: number;
  inputTokens: number | null;
  outputTokens: number | null;
  errorCode: string | null;
  createdAt: number;
}
/** The owner's current consent for one thread, read fresh from canonical bindings. */
export interface LearningConsent {
  ownerId: string;
  dotId: string;
  enrolled: boolean;
  learningEnabled: boolean;
  memoryAllowed: boolean;
}
/** Budget inputs for one claim. Every count is read inside the claiming transaction. */
export interface LearningClaimLimits {
  dayStart: number;
  dailyCalls: number;
  dailyTokens: number;
  dailyTimeoutMs: number;
  callTimeoutMs: number;
  dotDailyCalls: number;
  dotIntervalMs: number;
  reservedInputTokens: number;
  reservedOutputTokens: number;
}
export type LearningClaimSkip =
  | 'not_queued'
  | 'concurrent'
  | 'daily_calls'
  | 'daily_tokens'
  | 'daily_timeout'
  | 'dot_daily'
  | 'dot_interval';
export interface FinishedRun {
  run: ConversationRun;
  job: LearningJob | null;
  skipped: LearningJobSkip | null;
}
const learningJobCandidateSchema = z
  .object({
    signal: z.enum(LEARNING_SIGNALS),
    evidence: z
      .array(learningEvidenceRecordSchema)
      .min(1)
      .max(LEARNING_LIMITS.evidenceRecords),
    sourceDigest: z.string().regex(/^[0-9a-f]{64}$/),
    patternHash: z
      .string()
      .regex(/^[0-9a-f]{64}$/)
      .nullish(),
  })
  .strict();
