  admitInboundTurn(params: {
    platform: string;
    updateId: string;
    offset: number;
    threadId: string;
    dotId: string;
    ownerId: string;
    role: MessageRole;
    content: unknown;
    metadata?: unknown;
    source: AdmittedRunSource;
  }): { message: ConversationMessage; run: ConversationRun } | null {
    return this.transaction(() => {
      try {
        this.db
          .prepare(
            'INSERT INTO connector_inbound (platform, updateId, offset, createdAt) VALUES (?, ?, ?, ?)',
          )
          .run(params.platform, params.updateId, params.offset, Date.now());
      } catch (error) {
        if (isUniqueViolation(error)) return null;
        throw error;
      }
      const message = this.insertMessage(params);
      const run = this.insertRun(
        params.threadId,
        params.source,
        message.ordinal,
      );
      this.insertEvent(run.threadId, run.id, {
        type: 'RUN_STARTED',
        messageId: message.id,
      });
      return { message, run };
    });
  }
  // Durable dedup for redelivered platform updates: the (platform, updateId)
  // uniqueness constraint rejects the duplicate, not an application-level check.
  admitInbound(platform: string, updateId: string, offset: number): boolean {
    try {
      this.db
        .prepare(
          'INSERT INTO connector_inbound (platform, updateId, offset, createdAt) VALUES (?, ?, ?, ?)',
        )
        .run(platform, updateId, offset, Date.now());
      return true;
    } catch (error) {
      if (isUniqueViolation(error)) return false;
      throw error;
    }
  }
  highWaterOffset(platform: string): number | null {
    const row = this.db
      .prepare(
        'SELECT MAX(offset) AS offset FROM connector_inbound WHERE platform=?',
      )
      .get(platform) as { offset: number | null };
    return row.offset;
  }
  queueOutbound(
    threadId: string,
    runId: string | null,
    payload: unknown,
  ): ConnectorOutbound {
    const now = Date.now();
    const outbound: ConnectorOutbound = {
      id: randomUUID(),
      threadId,
      runId,
      status: 'pending',
      retryCount: 0,
      payload,
      error: null,
      createdAt: now,
      updatedAt: now,
    };
    this.db
      .prepare(
        "INSERT INTO connector_outbound (id, threadId, runId, status, payload, error, createdAt, updatedAt, retryCount) VALUES (?, ?, ?, 'pending', ?, NULL, ?, ?, 0)",
      )
      .run(outbound.id, threadId, runId, JSON.stringify(payload), now, now);
    return outbound;
  }
  outbound(id: string): ConnectorOutbound | undefined {
    const row = this.db
      .prepare('SELECT * FROM connector_outbound WHERE id=?')
      .get(id) as OutboundRow | undefined;
    return row ? toOutbound(row) : undefined;
  }
  pendingOutbound(threadId?: string): ConnectorOutbound[] {
    return (
      this.db
        .prepare(
          `SELECT * FROM connector_outbound WHERE status IN ('pending', 'attempting') ${threadId ? 'AND threadId=?' : ''} ORDER BY createdAt`,
        )
        .all(...(threadId ? [threadId] : [])) as unknown as OutboundRow[]
    ).map(toOutbound);
  }
  markOutbound(
    id: string,
    status: OutboundStatus,
    error: string | null = null,
  ): ConnectorOutbound {
    return this.transaction(() => {
      const current = this.outbound(id);
      if (!current) throw new Error('Outbound delivery not found.');
      const retryCount =
        status === 'failed' ? current.retryCount + 1 : current.retryCount;
      this.db
        .prepare(
          'UPDATE connector_outbound SET status=?, error=?, retryCount=?, updatedAt=? WHERE id=?',
        )
        .run(status, error, retryCount, Date.now(), id);
      return this.outbound(id)!;
    });
  }
